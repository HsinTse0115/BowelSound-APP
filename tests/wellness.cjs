const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const code = ts.transpileModule(fs.readFileSync('services/wellness.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {}, Date };
vm.runInNewContext(code, context);
const { dateKey, validDay, calendarDays, upsertDay, parseEntries } = context.exports;
assert.equal(validDay('2024-02-29'), true);
assert.equal(validDay('2026-02-29'), false);
assert.equal(validDay('2026-2-01'), false);
const feb = calendarDays(new Date(2024, 1, 1));
assert.equal(feb.filter(Boolean).length, 29);
assert.equal(feb.length % 7, 0);
assert.equal(feb[4], '2024-02-01');
assert.equal(calendarDays(new Date(2026, 1, 1))[0], '2026-02-01');
const today = dateKey();
let entries = upsertDay([], 'alice', today, { bowel: '今天沒有', note: ' hello ' });
entries = upsertDay(entries, 'bob', today, { feeling: '普通' });
const before = JSON.stringify(entries);
const checked = upsertDay(entries, 'alice', today, { habits: ['meal', 'meal', 'invalid'] });
assert.equal(JSON.stringify(entries), before);
assert.equal(checked.length, 2);
assert.equal(checked.find(e => e.patientId === 'alice').note, 'hello');
assert.equal(checked.find(e => e.patientId === 'alice').habits.join(','), 'meal');
assert.equal(checked.find(e => e.patientId === 'bob').feeling, '普通');
const updated = upsertDay(checked, 'alice', today, { note: 'changed', bowel: '未填寫' });
assert.equal(updated.find(e => e.patientId === 'alice').habits.join(','), 'meal');
assert.equal(parseEntries(JSON.stringify({ version: 1, entries: updated })).length, 2);
assert.equal(parseEntries(null).length, 0);
assert.throws(() => parseEntries('{bad json'));
assert.throws(() => parseEntries(JSON.stringify({ version: 2, entries: [] })));
assert.throws(() => parseEntries(JSON.stringify({ version: 1, entries: [{ date: '2026-13-01' }] })));
const tomorrow = new Date(); tomorrow.setDate(tomorrow.getDate() + 1);
assert.throws(() => upsertDay(entries, 'alice', dateKey(tomorrow), {}));
assert.throws(() => upsertDay(entries, '', today, {}));
assert.throws(() => upsertDay(entries, 'alice', today, { bowel: 'invalid' }));
console.log('Wellness tests passed: calendar boundaries, local dates, per-person isolation, partial merge, corruption rejection and immutable updates.');
const { bowelReminderEnd } = context.exports;
const streak = Array.from({ length: 3 }, (_, i) => ({ patientId: 'alice', date: dateKey(new Date(2026, 9, 13 + i)), bowel: '今天沒有' }));
assert.equal(bowelReminderEnd(streak, 'alice', '2026-10-15'), '2026-10-15');
assert.equal(bowelReminderEnd(streak, 'alice', '2026-10-16'), '2026-10-15');
assert.equal(bowelReminderEnd(streak.slice(1), 'alice', '2026-10-15'), null);
assert.equal(bowelReminderEnd(streak.filter((_, i) => i !== 1), 'alice', '2026-10-15'), null);
assert.equal(bowelReminderEnd(streak, 'bob', '2026-10-15'), null);
assert.equal(bowelReminderEnd(streak.map((e, i) => i === 1 ? { ...e, bowel: '未填寫' } : e), 'alice', '2026-10-15'), null);
assert.equal(bowelReminderEnd([...streak, { patientId: 'alice', date: '2026-10-16', bowel: '1 次' }], 'alice', '2026-10-16'), null);
assert.equal(bowelReminderEnd(streak, 'alice', '2026-10-17'), null);
const crossingMonth = Array.from({ length: 3 }, (_, i) => ({ patientId: 'alice', date: dateKey(new Date(2026, 8, 30 + i)), bowel: '今天沒有' }));
assert.equal(bowelReminderEnd(crossingMonth, 'alice', '2026-10-02'), '2026-10-02');
console.log('Reminder tests passed: 3-day threshold, gaps, missing data, profile isolation, recovery and month boundaries.');
